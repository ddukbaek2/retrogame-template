//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { GameModule } from "../../game/gamemodule.js";
import { PlayScreen } from "./screen/playscreen.js";


//==============================================================================
// 보기용 편. (게임 한 편이 어떻게 생겼는지 보여 주는 가장 작은 예)
//
// 이 틀에서 게임 한 편은 이렇게 이루어집니다.
//
//   src/games/<id>/<id>game.js   GameModule 을 물려받은 모듈. 진행과 저장을 들고 있습니다.
//   src/games/<id>/screen/       화면들. ScreenNode 를 물려받습니다.
//   src/games/<id>/logic/        규칙. 엔진도 브라우저도 들이지 않는 순수 함수입니다.
//
// 모듈을 만들었으면 두 곳에 한 줄씩 적습니다.
//   src/game/games.js      들여오기와 만들기
//   src/game/identity.js   그 편의 종이 색, 먹 색, 강조색
//
// 자세한 규약은 `docs/게임-모듈-규약.md` 에 있습니다.
//==============================================================================
export class SampleGame extends GameModule {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { object } */ #data;
	/** @private @type { PlayScreen } */ #playScreen;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 * @param { object } scene
	 */
	constructor(scene) {
		super(scene, "sample", "보기", "이 틀로 게임 한 편이 어떻게 생기는지 보여 주는 가장 작은 예입니다.");
		this.#data = this.readData(createDefaultData());
		this.#playScreen = null;
	}

	//==============================================================================
	// 화면 만들기.
	//==============================================================================
	/**
	 * @override
	 * @returns { object }
	 */
	createScreens() {
		this.#playScreen = new PlayScreen(this);
		return { play: this.#playScreen };
	}

	//==============================================================================
	// 들어갈 때 여는 화면.
	//==============================================================================
	/**
	 * @override
	 * @returns { string }
	 */
	getEntryKey() {
		return "play";
	}

	//==============================================================================
	// 진행을 지웠을 때.
	//==============================================================================
	/**
	 * @override
	 */
	onProgressErased() {
		this.#data = createDefaultData();
	}

	//==============================================================================
	// 지금까지 누른 수.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getCount() {
		return this.#data.count;
	}

	//==============================================================================
	// 한 번 셈. (누를 때마다 늘고 저장합니다)
	//==============================================================================
	countUp() {
		this.#data.count += 1;
		if (this.#data.count > this.#data.best) {
			this.#data.best = this.#data.count;
		}
		this.writeData(this.#data);
	}

	//==============================================================================
	// 가장 많이 눌렀던 수.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getBest() {
		return this.#data.best;
	}

	//==============================================================================
	// 처음부터.
	//==============================================================================
	resetCount() {
		this.#data.count = 0;
		this.writeData(this.#data);
	}
}


//==============================================================================
// 저장 기본값. (`readData` 가 저장된 것이 없을 때 이것을 씁니다)
//==============================================================================
/**
 * @returns { object }
 */
function createDefaultData() {
	return { count: 0, best: 0 };
}
