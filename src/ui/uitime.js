const System = globalThis;


//==============================================================================
// UI 시간. (깜빡임, 숨쉬기처럼 프레임과 무관하게 흐르는 연출에 씁니다)
//==============================================================================


let uiElapsedSeconds = 0;


//==============================================================================
// 갱신. (씬의 tick 에서 한 번)
//==============================================================================
/**
 * @param { number } timeDelta
 */
export function tickUiTime(timeDelta) {
	uiElapsedSeconds += timeDelta;
}


//==============================================================================
// 경과 시간 반환.
//==============================================================================
/**
 * @returns { number }
 */
export function readUiElapsedSeconds() {
	return uiElapsedSeconds;
}
