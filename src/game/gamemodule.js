const System = globalThis;
import { readGameData, writeGameData } from "./savedata.js";
import { readGameIdentity } from "./identity.js";


//==============================================================================
// 게임 모듈 바탕.
//
// 이 프로젝트가 만드는 게임 한 편이 모듈 하나입니다. 모듈은 제 화면들을 만들어 씬에 맡기고,
// 제 진행을 제 이름으로 저장합니다. 타이틀에서 들어가고 게임 안의 메뉴에서 "타이틀로" 나옵니다.
//
// 파생 모듈이 채우는 것.
//   async load()          자료 받기 (선택)
//   createScreens()       { 화면 이름: ScreenNode }, 씬이 "<게임 id>:<이름>" 으로 등록합니다
//   getEntryKey()         들어갈 때 여는 화면 이름
//   onEnter()             타이틀에서 들어올 때 (선택)
//
// 화면은 ScreenNode 를 상속하고 생성자에 이 모듈을 넘겨 받습니다. 화면이 부르는 길 찾기
// (다음 화면, 나가기, 설정)는 모듈의 메서드입니다. 씬을 직접 부르지 않습니다.
//==============================================================================
export class GameModule {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { object } */ #scene;
	/** @private @type { string } */ #id;
	/** @private @type { string } */ #name;
	/** @private @type { string } */ #describe;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 * @param { object } scene
	 * @param { string } id 영문 소문자 식별자. (화면 이름, 저장 이름의 접두사)
	 * @param { string } name 화면에 보이는 이름.
	 * @param { string } describe 한 줄 설명.
	 */
	constructor(scene, id, name, describe) {
		this.#scene = scene;
		this.#id = id;
		this.#name = name;
		this.#describe = describe;
	}

	/** @returns { object } */
	getScene() {
		return this.#scene;
	}

	/** @returns { string } */
	getId() {
		return this.#id;
	}

	/** @returns { string } */
	getName() {
		return this.#name;
	}

	/** @returns { string } */
	getDescribe() {
		return this.#describe;
	}

	//==============================================================================
	// 이 게임의 종이, 먹, 강조색. (앱이 들어갈 때 Colors 에 되짚어 칩니다)
	//
	// 값은 `src/game/identity.js` 에서 정합니다. 파생 모듈이 덮어써도 됩니다.
	//==============================================================================
	/**
	 * @returns { object | null } { paper, ink, accent }
	 */
	getPalette() {
		const identity = readGameIdentity();
		return identity;
	}

	//==============================================================================
	// 자료 받기. (선택, 파생 모듈이 덮어씁니다)
	//==============================================================================
	async load() {

	}

	//==============================================================================
	// 화면 만들기. (파생 모듈이 채웁니다)
	//==============================================================================
	/**
	 * @returns { object } { 화면 이름: ScreenNode }
	 */
	createScreens() {
		return {};
	}

	//==============================================================================
	// 들어갈 때 여는 화면 이름.
	//==============================================================================
	/**
	 * @returns { string }
	 */
	getEntryKey() {
		return "main";
	}

	//==============================================================================
	// 타이틀에서 들어올 때. (선택)
	//==============================================================================
	onEnter() {

	}

	//==============================================================================
	// 설정에서 진행을 지웠을 때. (선택, 들고 있는 진행을 기본값으로 되돌립니다)
	//==============================================================================
	onProgressErased() {

	}

	//==============================================================================
	// 제 화면으로 옮기기.
	//==============================================================================
	/**
	 * @param { string } localKey
	 */
	changeScreen(localKey) {
		this.#scene.changeScreen(this.#id + ":" + localKey);
	}

	//==============================================================================
	// 타이틀로 나가기.
	//==============================================================================
	exit() {
		this.#scene.goTitle();
	}

	//==============================================================================
	// 설정 열기. (돌아오면 지금 화면)
	//==============================================================================
	openSettings() {
		this.#scene.openSettings();
	}

	/** @returns { object } */
	getSettings() {
		return this.#scene.getSettings();
	}

	//==============================================================================
	// 이 게임만의 설정 항목. (설정 화면이 틀 항목 앞에 끼워 넣습니다)
	//
	// 설정 화면은 하나입니다. 게임이 따로 설정 화면을 만들지 않습니다. 여기에 항목을 내면
	// 타이틀에서 열든 게임 안에서 열든 같은 자리에 함께 섭니다.
	// 돌려주는 것은 `{ id, label, valueText }` 의 배열입니다. valueText 는 없어도 됩니다.
	//==============================================================================
	/**
	 * @returns { Array }
	 */
	createSettingItems() {
		return [];
	}

	//==============================================================================
	// 그 항목을 고쳤을 때. (direction 은 좌우, 확인은 1)
	//==============================================================================
	/**
	 * @param { string } itemId
	 * @param { number } direction
	 * @returns { boolean } 이 게임이 처리했으면 true.
	 */
	handleSettingItem(itemId, direction) {
		return false;
	}

	//==============================================================================
	// 틀이 내는 설정 항목의 이름. (여러 말을 지원하는 게임이 제 말로 바꿔 답합니다)
	//==============================================================================
	/**
	 * @param { string } itemId
	 * @param { string } defaultLabel
	 * @returns { string }
	 */
	readSettingLabel(itemId, defaultLabel) {
		return defaultLabel;
	}

	//==============================================================================
	// 틀이 내는 설정 항목의 값. (여러 말을 지원하는 게임이 제 말로 바꿔 답합니다)
	//
	// `valueKey` 는 그 값의 열쇠입니다. 켜고 끄는 것은 "on", "off" 이고,
	// 고르는 것은 그 항목 표의 id 입니다. ("fit", "integer", "256", "medium" 같은 것)
	// 볼록 효과를 고를 수 없을 때는 "unavailable" 입니다.
	//==============================================================================
	/**
	 * @param { string } itemId
	 * @param { string } valueKey
	 * @param { string } defaultText
	 * @returns { string }
	 */
	readSettingValue(itemId, valueKey, defaultText) {
		return defaultText;
	}

	//==============================================================================
	// 설정 화면의 제목과 아래 안내 줄. (여러 말을 지원하는 게임이 제 말로 바꿔 답합니다)
	//
	// `partId` 는 "title" 또는 "hint" 입니다.
	//==============================================================================
	/**
	 * @param { string } partId
	 * @param { string } defaultText
	 * @returns { string }
	 */
	readSettingText(partId, defaultText) {
		return defaultText;
	}

	//==============================================================================
	// 명령을 지금 누르고 있는지. (실시간 게임의 화면이 tick 마다 읽습니다, 방향, 확인, 취소)
	//==============================================================================
	/**
	 * @param { string } command
	 * @returns { boolean }
	 */
	isCommandHeld(command) {
		const isHeld = this.#scene.isCommandHeld(command);
		return isHeld;
	}

	//==============================================================================
	// 진행 읽기, 쓰기. (게임마다 제 이름으로 localStorage 에)
	//==============================================================================
	/**
	 * @param { object } defaultData
	 * @returns { object }
	 */
	readData(defaultData) {
		return readGameData(this.#id, defaultData);
	}

	/**
	 * @param { object } data
	 */
	writeData(data) {
		writeGameData(this.#id, data);
	}
}
